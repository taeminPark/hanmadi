def expand():
    out=[]
    def add(id,category,situation,text,intent,**fields):
        out.append({**dict(id=id,category=category,situation=situation,text=text,tone='정중',target='',tags=[intent],source='builtin',lead='',response=''),**fields})
    for si,(situation,rows) in enumerate(SITUATIONS.items(),1):
        for ti,target in enumerate(['기관장/임원','부서장','선배','동료','후배'],1):
            for ri,(intent,formal,fun) in enumerate(rows,1):
                for tone,text in [('정중',formal),('유쾌',fun)]:
                    add(f'expanded_s{si:02}_{ti}_{ri}_{tone}','situation',situation,text,intent,target=target,tone=tone)
    for si,(situation,rows) in enumerate(CRISES.items(),1):
        for ti,target in enumerate(['윗사람','동료·후배'],1):
            for ri,(intent,text) in enumerate(rows,1):
                add(f'expanded_c{si:02}_{ti}_{ri}','crisis',situation,text,intent,target=target)
    for si,(situation,moments) in enumerate(EVENTS.items(),1):
        for moment,texts in moments.items():
            for ti,target in enumerate(['윗사람','동료·후배'],1):
                for ri,text in enumerate(texts,1):
                    add(f'expanded_e{si:02}_{moment}_{ti}_{ri}','event',situation,text,f'{moment}_{ri}',target=target,moment=moment)
    for si,(situation,styles) in enumerate(TOASTS.items(),1):
        for style,items in styles.items():
            for ri,item in enumerate(items,1):
                text,lead,response=item if isinstance(item,tuple) else (item,'','')
                add(f'expanded_t{si:02}_{style}_{ri}','toast',situation,text,f'{style}_{ri}',style=style,tone='',lead=lead,response=response)
    for si,(situation,texts) in enumerate(TARGET_SPECIFIC.items(),1):
        assert len(texts)==5
        for ti,(target,text) in enumerate(zip(['기관장/임원','부서장','선배','동료','후배'],texts),1):
            add(f'expanded_relation_{si:02}_{ti}','situation',situation,text,'상대맞춤',target=target)
    for si,(situation,texts) in enumerate(SHORT.items(),1):
        for ti,target in enumerate(['기관장/임원','부서장','선배','동료','후배'],1):
            for ri,text in enumerate(texts,1):
                add(f'expanded_short_{si:02}_{ti}_{ri}','situation',situation,text,['상황설명','대안제안','다음행동'][ri-1],target=target,tone='짧게')
